'use strict';
/* The design system.
 *
 * Quansiox's stylesheet used to carry a colour layer that CLAIMED to be
 * extracted from Grok Bot 0.71.2. It was not: every token name in it
 * (--text-and-icon-primary, --background-primary, --fill-tsp-gray-main,
 * --function-neutral, --button-primary) is absent from Grok Bot's shipped
 * CSS. The app therefore kept the old look no matter what the header said.
 *
 * These tests pin the real thing:
 *   - the token layer is GENERATED from Grok's shipped bundle;
 *   - it contains Grok's real vocabulary (--cursor-*, --sand-*);
 *   - it contains none of the invented names;
 *   - every alias resolves to a token that actually exists;
 *   - every custom property the component rules use is defined.
 *
 * Electron-free. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const TOKENS = path.join(ROOT, 'src', 'renderer', 'grok-tokens.css');
const STYLES = path.join(ROOT, 'src', 'renderer', 'styles.css');
const SURFACES = path.join(ROOT, 'src', 'renderer-src', 'surfaces', 'surfaces.css');

const results = [];
function check(name, fn) {
  try {
    fn();
    results.push(`  ok   ${name}`);
  } catch (error) {
    results.push(`  FAIL ${name}\n       ${error?.message ?? error}`);
    process.exitCode = 1;
  }
}

const tokenCss = fs.readFileSync(TOKENS, 'utf8');
const styleCss = fs.readFileSync(STYLES, 'utf8');
const surfaceCss = fs.existsSync(SURFACES) ? fs.readFileSync(SURFACES, 'utf8') : '';

check('the token layer is generated from Grok Bot, not hand-written', () => {
  assert.match(tokenCss, /GENERATED by scripts\/extract-grok-tokens\.js/);
  assert.match(tokenCss, /Grok Bot 0\.75\.0/);
});

check('it carries Grok\'s real vocabulary', () => {
  const cursorTokens = (tokenCss.match(/--cursor-[a-zA-Z0-9-]+\s*:/g) || []).length;
  const sandTokens = (tokenCss.match(/--sand-[a-zA-Z0-9-]+\s*:/g) || []).length;
  assert.ok(cursorTokens >= 400, `expected Grok's base palette (--cursor-*), found ${cursorTokens}`);
  assert.ok(sandTokens >= 260, `expected Grok's product theme (--sand-*) in both themes, found ${sandTokens}`);
});

check('no invented token carries a literal colour', () => {
  // The legacy names may survive as ALIASES in the generated layer, but only
  // ever pointing at a real Grok token — never at a hand-picked colour.
  const invented = [
    '--text-and-icon-primary', '--text-and-icon-secondary', '--background-primary',
    '--background-secondary', '--fill-tsp-gray-main', '--fill-tsp-white-main',
    '--function-neutral', '--function-error', '--function-success', '--function-warning',
    '--button-primary', '--button-primary-foreground', '--button-secondary',
    '--button-destructive', '--segmented-selected',
  ];
  const sand = new Set([
    ...(tokenCss.match(/--sand-[a-zA-Z0-9-]+\s*:/g) || []).map((s) => s.replace(/\s*:$/, '')),
  ]);
  for (const name of invented) {
    // In the component stylesheet it must not exist at all.
    assert.equal(
      new RegExp(`${name}\\s*:`).test(styleCss), false,
      `${name} must not be declared in the component stylesheet`,
    );
    // In the generated layer it may exist, but only as a var() to a real token.
    const m = tokenCss.match(new RegExp(`${name}\\s*:\\s*([^;]+);`));
    if (!m) continue;
    const value = m[1].trim();
    if (value.startsWith('var(')) {
      const target = value.match(/var\((--[a-zA-Z0-9-]+)/)?.[1];
      assert.ok(target && sand.has(target), `${name} points at ${target}, which is not a Grok sand token`);
    } else {
      assert.fail(`${name} is declared as a literal (${value}) — it must alias a Grok token`);
    }
  }
});

check('the light and dark sand themes are both present', () => {
  assert.match(tokenCss, /:root \{[\s\S]*--sand-bg-pane/);
  assert.match(tokenCss, /html\[data-theme='dark'\] \{[\s\S]*--sand-bg-pane/);
  // Grok's real values, resolved by Grok's own 0.75.0 runtime resolver.
  assert.match(tokenCss, /--sand-bg-pane: #ffffff/);
  assert.match(tokenCss, /--sand-bg-pane: #161616/);
  assert.match(tokenCss, /--sand-bg-accent-primary: #1680f3/);
  assert.match(tokenCss, /--sand-bg-accent-primary: #116dd2/);
});

check('every alias resolves to a token that exists', () => {
  const defined = new Set([
    ...(tokenCss.match(/(--[a-zA-Z0-9-]+)\s*:/g) || []).map((s) => s.replace(/\s*:$/, '')),
  ]);
  const aliases = [...tokenCss.matchAll(/^\s{2}(--[a-zA-Z0-9-]+):\s*var\((--[a-zA-Z0-9-]+)\);/gm)];
  assert.ok(aliases.length >= 40, `expected a real alias layer, found ${aliases.length}`);
  for (const [, alias, target] of aliases) {
    assert.ok(defined.has(target), `${alias} points at ${target}, which is not defined`);
  }
});

check('every custom property the component rules use is defined', () => {
  const defined = new Set();
  for (const css of [tokenCss, styleCss, surfaceCss]) {
    for (const m of css.matchAll(/(--[a-zA-Z0-9-]+)\s*:/g)) defined.add(m[1]);
  }
  const used = new Set();
  for (const css of [styleCss, surfaceCss]) {
    for (const m of css.matchAll(/var\(\s*(--[a-zA-Z0-9-]+)/g)) used.add(m[1]);
  }
  for (const css of ['src/renderer-src', 'src/renderer-src/cards', 'src/renderer-src/surfaces']) {
    const dir = path.join(ROOT, css);
    if (!fs.existsSync(dir)) continue;
    for (const file of fs.readdirSync(dir)) {
      if (!/\.(jsx?|mjs)$/.test(file)) continue;
      const text = fs.readFileSync(path.join(dir, file), 'utf8');
      for (const m of text.matchAll(/var\(\s*(--[a-zA-Z0-9-]+)/g)) used.add(m[1]);
    }
  }
  const missing = [...used].filter((name) => !defined.has(name));
  assert.deepEqual(missing, [], `these are used but never defined: ${missing.join(', ')}`);
});

check('the stylesheet imports the generated layer before its own rules', () => {
  const importAt = styleCss.indexOf("@import './grok-tokens.css';");
  assert.ok(importAt >= 0, 'the generated token layer must be imported');
  const firstRule = styleCss.indexOf(':root {');
  assert.ok(importAt < firstRule, 'the token layer must come first so it owns the colour names');
});

check('the generated layer is not hand-edited into the component stylesheet', () => {
  // The component stylesheet must not declare a COLOUR of its own. The type
  // ramp (--text-xs … --text-xl) is Quansiox's own and is allowed.
  const TYPE_RAMP = new Set(['--text-xs', '--text-sm', '--text-base', '--text-md', '--text-lg', '--text-xl']);
  const colourDecls = (styleCss.match(/^\s*(--[a-zA-Z0-9-]+)\s*:/gm) || [])
    .map((d) => d.replace(/\s*:$/, ''))
    .filter((name) => !TYPE_RAMP.has(name))
    .filter((name) => /^(--(bg|text|stroke|accent|line|surface|canvas|sidebar|fg|muted|faint|success|warn|danger|info|ok|warning|button|function|fill|border|message|logo|shadow|segmented|background)-)/.test(name));
  assert.deepEqual(colourDecls, [], 'the component stylesheet must not declare colours');
});

check('the shipped Grok typefaces are vendored and declared', () => {
  for (const f of ['X-VF.woff2', 'XMono-VF.woff2', 'cursor-icons-16.woff2']) {
    const p = path.join(ROOT, 'src', 'renderer', 'fonts', f);
    assert.ok(fs.existsSync(p), `missing vendored font ${f}`);
    assert.ok(fs.statSync(p).size > 5000, `${f} looks truncated`);
  }
  const fontCss = fs.readFileSync(path.join(ROOT, 'src', 'renderer', 'grok-fonts.css'), 'utf8');
  for (const re of [/font-family: ?XVF;/, /font-family: ?XVF Mono;/, /font-family: ?cursor-icons;/]) {
    assert.match(fontCss, re);
  }
  // Grok's stacks lead with its own faces (the runtime typography table).
  assert.match(styleCss, /--font-sans: 'XVF', -apple-system/);
  assert.match(styleCss, /--font-mono: 'XVF Mono', ui-monospace/);
});

check('the generator refuses an alias that points at a token Grok does not have', () => {
  const { ALIASES } = require('../scripts/extract-grok-tokens.js');
  const themes = JSON.parse(fs.readFileSync(
    '/Users/mohsin/manux/quansiox/work/grok-re/case/grok-design-tokens-0.75.0.json', 'utf8',
  ));
  // A target is legal if it exists in Grok's resolved themes, in Grok's
  // shipped base palette, or is itself an earlier alias in the layer.
  const { findGrokCss } = require('../scripts/extract-grok-tokens.js');
  const css = fs.readFileSync(findGrokCss(), 'utf8');
  const baseNames = new Set((css.match(/--[a-zA-Z0-9-]+(?=\s*:)/g) ?? []));
  const aliasNames = new Set(ALIASES.map(([a]) => a));
  const known = new Set([...Object.keys(themes.light ?? {}), ...Object.keys(themes.dark ?? {}), ...baseNames, ...aliasNames]);
  for (const [alias, target] of ALIASES) {
    if (!target.startsWith('--')) continue;
    assert.ok(known.has(target), `${alias} points at ${target}, which is not in Grok's theme`);
  }
});

console.log(results.join('\n'));
if (process.exitCode) {
  console.error('\ndesign-system tests FAILED');
  process.exit(1);
}
console.log(`\ndesign system: ${results.length} checks OK`);
