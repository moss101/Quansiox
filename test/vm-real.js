'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const profile=fs.mkdtempSync(path.join(os.tmpdir(),'qx-parity-vm-adapter-'));
process.env.QUANSIOX_USER_DATA_DIR=profile;
const root=process.env.QUANSIOX_TEST_APP_ROOT || path.resolve(__dirname,'..');
const {settingsService}=require(path.join(root,'src/main/services/settingsService'));
settingsService.save({workspaceRoot:profile,sandboxMode:'vm'});
const {sandboxService}=require(path.join(root,'src/main/services/sandboxService'));
const {vmSandbox}=require(path.join(root,'src/main/services/vmSandboxService'));
let timer=setTimeout(()=>{vmSandbox.stopVm('vm-acceptance');console.error('VM acceptance timed out');process.exit(1);},15000);
(async()=>{
 const report={before:sandboxService.describe('vm-acceptance'),available:vmSandbox.available()};
 const entry=await sandboxService.ensure('vm-acceptance');
 report.entry={kind:entry.kind,status:entry.status,pid:entry.proc?.pid};
 report.uname=await sandboxService.call(entry,'exec',{command:'uname -s; uname -m'},'vm-acceptance');
 report.write=await sandboxService.call(entry,'fs.write',{p:'vm-proof.txt',content:'guest wrote this'},'vm-acceptance');
 report.read=await sandboxService.call(entry,'fs.read',{p:'vm-proof.txt'},'vm-acceptance');
 report.list=await sandboxService.call(entry,'fs.listdir',{p:'.'},'vm-acceptance');
 report.fileOnHost=fs.readFileSync(path.join(entry.root,'vm-proof.txt'),'utf8');
 assert.equal(report.uname.output,'Linux\naarch64');assert.deepEqual(report.write,{bytes:16});assert.equal(report.read,'guest wrote this');assert.deepEqual(report.list,[{name:'vm-proof.txt',dir:false}]);
 report.emptyExec=await sandboxService.call(entry,'exec',{command:'true'},'vm-acceptance');
 assert.deepEqual(report.emptyExec,{exitCode:0,output:''});
 await sandboxService.call(entry,'fs.write',{p:'empty.txt',content:''},'vm-acceptance');
 report.emptyRead=await sandboxService.call(entry,'fs.read',{p:'empty.txt'},'vm-acceptance');
 assert.equal(report.emptyRead,'');
 await assert.rejects(sandboxService.call(entry,'fs.read',{p:'missing.txt'},'vm-acceptance'));
 report.passed=true;
 report.describeAfterBoot=sandboxService.describe('vm-acceptance');report.sandboxStatus=sandboxService.status();report.vmStatus=vmSandbox.status();
 if(process.env.QUANSIOX_VM_REPORT) fs.writeFileSync(process.env.QUANSIOX_VM_REPORT,JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
})().catch(e=>{console.error(e.message);process.exitCode=1;}).finally(()=>{clearTimeout(timer);vmSandbox.stopVm('vm-acceptance');fs.rmSync(profile,{recursive:true,force:true});});
