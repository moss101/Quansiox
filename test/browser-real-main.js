'use strict';
const {app,BrowserWindow}=require('electron');const fs=require('node:fs'),path=require('node:path'),http=require('node:http');
const os=require('node:os');
process.env.QUANSIOX_USER_DATA_DIR=fs.mkdtempSync(path.join(os.tmpdir(),'qx-browser-real-'));
app.setPath('userData',process.env.QUANSIOX_USER_DATA_DIR);
const root=process.env.QUANSIOX_TEST_APP_ROOT || path.resolve(__dirname,'..');
const assert=require('node:assert/strict');const report={};let server,host;
app.commandLine.appendSwitch('disable-gpu');
const timeout=setTimeout(()=>{console.error('browser verification timed out');app.exit(1);},15000);
app.whenReady().then(async()=>{
 const {settingsService}=require(path.join(root,'src/main/services/settingsService'));settingsService.save({allowBrowser:true,workspaceRoot:process.env.QUANSIOX_USER_DATA_DIR});
 server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end('<!doctype html><title>Local acceptance fixture</title><button id="save" onclick="this.textContent=\'Saved\'">Save</button><label>Email<input id="email" aria-label="Email"></label>');});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const {browserService}=require(path.join(root,'src/main/services/browserService'));
 try{
  report.open=await browserService.open('browser-acceptance',{url:`http://127.0.0.1:${server.address().port}`});
  // GPA G6: a hidden window (never shown) must accept real background input.
  host=new BrowserWindow({width:1000,height:700,show:false});browserService.attachWindow('browser-acceptance',host);
  await new Promise(r=>setTimeout(r,200));
  report.hiddenSnapshot=await browserService.snapshot('browser-acceptance');
  assert.ok(report.hiddenSnapshot.refCount > 0, 'hidden snapshot must expose actionable geometry');
  const refFor=(snap,role,name)=>snap.text.split('\n').find(line=>line.includes('- '+role+' "'+name+'"'))?.match(/ref=(e\d+)/)?.[1];
  const hiddenButton=refFor(report.hiddenSnapshot,'button','Save');assert.ok(hiddenButton);
  report.backgroundClick=await browserService.act('browser-acceptance','click',{ref:hiddenButton,snapshot_id:report.hiddenSnapshot.snapshotId});
  report.backgroundButtonText=await browserService.act('browser-acceptance','js',{code:'document.querySelector("#save").textContent'});
  assert.equal(report.backgroundButtonText,'Saved','background click must land on the hidden page');
  const hiddenNext=await browserService.snapshot('browser-acceptance');
  const hiddenInput=refFor(hiddenNext,'textbox','Email');assert.ok(hiddenInput);
  report.backgroundType=await browserService.act('browser-acceptance','type',{ref:hiddenInput,text:'hidden@example.test',snapshot_id:hiddenNext.snapshotId});
  report.backgroundValue=await browserService.act('browser-acceptance','js',{code:'document.querySelector("#email").value'});
  assert.equal(report.backgroundValue,'hidden@example.test','background typing must land on the hidden page');
  host.showInactive();await new Promise(r=>setTimeout(r,200));
  report.snapshot=await browserService.snapshot('browser-acceptance');
  assert.ok(report.snapshot.refCount > 0, 'snapshot must expose actionable geometry');
  const button=refFor(report.snapshot,'button','Saved');assert.ok(button);
  report.click=await browserService.act('browser-acceptance','click',{ref:button,snapshot_id:report.snapshot.snapshotId});
  report.buttonText=await browserService.act('browser-acceptance','js',{code:'document.querySelector("#save").textContent'});assert.equal(report.buttonText,'Saved');
  const next=await browserService.snapshot('browser-acceptance');
  const input=refFor(next,'textbox','Email');assert.ok(input);
  report.fill=await browserService.act('browser-acceptance','fill',{ref:input,value:'fixture@example.test',snapshot_id:next.snapshotId});
  report.inputValue=await browserService.act('browser-acceptance','js',{code:'document.querySelector("#email").value'});assert.equal(report.inputValue,'fixture@example.test');
  const beforeNavigation=await browserService.snapshot('browser-acceptance');
  await browserService.open('browser-acceptance',{url:`http://127.0.0.1:${server.address().port}/next`});
  report.staleNavigation=await browserService.act('browser-acceptance','click',{ref:button,snapshot_id:beforeNavigation.snapshotId});
  assert.equal(report.staleNavigation.__browserError,'STALE_PAGE');
  await browserService.act('browser-acceptance','js',{code:'document.cookie="childA=private; path=/"; localStorage.setItem("childSecret","A")'});
  await browserService.open('browser-sibling',{url:`http://127.0.0.1:${server.address().port}`});
  report.siblingCookies=await browserService.act('browser-sibling','js',{code:'document.cookie'});
  report.siblingStorage=await browserService.act('browser-sibling','js',{code:'localStorage.getItem("childSecret")'});
  assert.equal(report.siblingCookies,'');assert.equal(report.siblingStorage,'null');
  const sessionA=browserService._activeTab('browser-acceptance').view.webContents.session;
  const sessionB=browserService._activeTab('browser-sibling').view.webContents.session;
  assert.notEqual(sessionA,sessionB,'siblings must have independent Chromium sessions');
  await browserService.tabs('browser-acceptance','new',{url:`http://127.0.0.1:${server.address().port}`});
  assert.equal(await browserService.act('browser-acceptance','js',{code:'localStorage.getItem("childSecret")'}),'A','tabs within one task share its own storage');
  assert.equal(sessionA.listenerCount('will-download'),1,'one download handler per session, not per tab');
  report.storageIsolated=true;report.passed=true;
 }catch(e){report.error=e.message;}
 report.state=browserService.state('browser-acceptance');
 if(process.env.QUANSIOX_BROWSER_REPORT) fs.writeFileSync(process.env.QUANSIOX_BROWSER_REPORT,JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
 browserService.destroy('browser-acceptance');browserService.destroy('browser-sibling');host?.destroy();server.close();clearTimeout(timeout);app.exit(report.passed ? 0 : 1);
}).catch(e=>{console.error(e.message);server?.close();clearTimeout(timeout);app.exit(1);});
